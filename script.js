// ==========================
// WEBSITE NAVIGATION
// ==========================

const pages = [
  "home",
  "characters",
  "world",
  "documents",
  "article"
];

const categoryNames = {
  characters: "PERSONNEL FILE",
  world: "WORLD RECORD",
  documents: "ARCHIVED DOCUMENT"
};

let previousPage = "characters";

function showPage(pageName) {
  if (!pages.includes(pageName)) return;

  pages.forEach(name => {
    document.getElementById("page-" + name).hidden =
      name !== pageName;
  });

  document.querySelectorAll(".nav-link").forEach(button => {
    const active = button.dataset.page === pageName;

    button.classList.toggle("active", active);

    if (active) {
      button.setAttribute("aria-current", "page");
    } else {
      button.removeAttribute("aria-current");
    }
  });

  window.scrollTo({
    top: 0,
    behavior: "instant"
  });
}


// ==========================
// ARCHIVE LIST & SEARCH
// ==========================

function renderList(category, containerId, searchTerm = "") {

  const container = document.getElementById(containerId);
  container.replaceChildren();

  const filtered = records.filter(record =>
    record.category === category &&
    (
      record.title + " " +
      record.id + " " +
      record.summary
    )
      .toLocaleLowerCase()
      .includes(searchTerm.trim().toLocaleLowerCase())
  );

  if (filtered.length === 0) {
    const message = document.createElement("p");
    message.className = "empty-state";
    message.textContent = "没有找到符合条件的档案。";
    container.appendChild(message);
    return;
  }

  filtered.forEach(record => {

    const button = document.createElement("button");
    button.type = "button";
    button.className = "record-row";

    const body = document.createElement("span");

    const id = document.createElement("span");
    id.className = "record-id";
    id.textContent = record.id;

    const title = document.createElement("strong");
    title.className = "record-title";
    title.textContent = record.title;

    const summary = document.createElement("span");
    summary.className = "record-summary";
    summary.textContent = record.summary;

    const arrow = document.createElement("span");
    arrow.className = "record-arrow";
    arrow.setAttribute("aria-hidden", "true");
    arrow.textContent = "↗";

    body.append(id, title, summary);
    button.append(body, arrow);

    button.addEventListener("click", () => {
      openArticle(record);
    });

    container.appendChild(button);

  });
}


// ==========================
// ARTICLE VIEW
// ==========================

function openArticle(record) {

  previousPage = record.category;

  document.getElementById("article-path").textContent =
    record.id;

  document.getElementById("article-type").textContent =
    categoryNames[record.category];

  document.getElementById("article-title").textContent =
    record.title;

  document.getElementById("article-id").textContent =
    "档案编号 / " + record.id;

  document.getElementById("article-summary").textContent =
    record.summary;

  showPage("article");
}


// ==========================
// EVENT LISTENERS
// ==========================

document.querySelectorAll("[data-page]").forEach(button => {
  button.addEventListener("click", () => {
    showPage(button.dataset.page);
  });
});

document.getElementById("back-button").addEventListener(
  "click",
  () => showPage(previousPage)
);

document.getElementById("character-search").addEventListener(
  "input",
  event => {
    renderList(
      "characters",
      "characters-list",
      event.target.value
    );
  }
);


// ==========================
// INITIALIZATION
// ==========================

renderList("characters", "characters-list");
renderList("world", "world-list");
renderList("documents", "documents-list");

showPage("home");
